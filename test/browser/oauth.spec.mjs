import { test, expect } from "@playwright/test";
import { createHash, randomBytes } from "node:crypto";

const origin = "http://127.0.0.1:8791";
const cookiesOf = response => response.headersArray().filter(header => header.name.toLowerCase() === "set-cookie").map(header => header.value.split(";")[0]).join("; ");
test("OAuth PKCE consent, token audience, remote tools and replay protection", async ({ request, page }) => {
  const challenge = await request.post("/mcp", { data: { jsonrpc: "2.0", id: 1, method: "tools/list" } });
  expect(challenge.status()).toBe(401);
  expect(challenge.headers()["www-authenticate"]).toContain("scout:chat");
  expect((await request.get("/.well-known/oauth-authorization-server")).ok()).toBe(true);
  const registration = await request.post("/oauth/register", { data: { client_name: "Synthetic OAuth test", redirect_uris: ["http://localhost:9876/callback"], grant_types: ["authorization_code", "refresh_token"], response_types: ["code"], token_endpoint_auth_method: "none" } });
  expect(registration.status()).toBe(201);
  const client = await registration.json();
  const pair = await (await request.post("/api/pair/start", { data: { client: "synthetic-oauth" } })).json();
  const approved = await request.post("/api/pair/approve", { data: { code: pair.code, name: "Synthetic OAuth workspace" } });
  expect(approved.ok()).toBe(true);
  const browserCookie = cookiesOf(approved);
  const link = await (await request.post("/api/link/start", { headers: { origin, cookie: browserCookie }, data: {} })).json();
  const collected = await request.post("/api/link/poll", { headers: { origin }, data: { poll_token: link.poll_token } });
  const deviceCookie = cookiesOf(collected);
  expect(deviceCookie).toContain("scout_dev=");
  const verifier = randomBytes(32).toString("base64url");
  const authorization = "/authorize?" + new URLSearchParams({ client_id: client.client_id, redirect_uri: "http://localhost:9876/callback", response_type: "code", scope: "scout:chat", state: "synthetic-state", code_challenge: createHash("sha256").update(verifier).digest("base64url"), code_challenge_method: "S256", resource: `${origin}/mcp` });
  const consent = await request.get(authorization, { headers: { cookie: deviceCookie } });
  expect(consent.status()).toBe(200);
  const html = await consent.text();
  const handle = /name="handle" value="([^"]+)"/.exec(html)?.[1];
  expect(handle).toBeTruthy();
  const cookie = [deviceCookie, cookiesOf(consent)].join("; ");
  await page.setExtraHTTPHeaders({ cookie: deviceCookie });
  await page.goto(authorization);
  await expect(page.locator("#allow")).toBeEnabled();
  await page.screenshot({ path: "test-results/oauth-consent.png", fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const grant = await request.post("/authorize", { headers: { origin, cookie }, form: { handle, decision: "approve" }, maxRedirects: 0 });
  expect(grant.status()).toBe(302);
  const redirect = new URL(grant.headers().location);
  expect(redirect.searchParams.get("state")).toBe("synthetic-state");
  const tokenResponse = await request.post("/oauth/token", { form: { grant_type: "authorization_code", client_id: client.client_id, code: redirect.searchParams.get("code"), redirect_uri: "http://localhost:9876/callback", code_verifier: verifier } });
  expect(tokenResponse.ok()).toBe(true);
  const token = await tokenResponse.json();
  const result = await request.post("/mcp", { headers: { authorization: `Bearer ${token.access_token}` }, data: { jsonrpc: "2.0", id: 1, method: "tools/list" } });
  expect(result.status()).toBe(200);
  expect((await result.json()).result.tools.map(tool => tool.name)).toEqual(["scout_log_chat", "scout_status"]);
  const replay = await request.post("/authorize", { headers: { origin, cookie }, form: { handle, decision: "approve" }, maxRedirects: 0 });
  expect(replay.status()).toBe(400);
});
